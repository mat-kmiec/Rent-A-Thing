package pl.rentathing.user.entity;

/**
 * The Role enum represents the roles that can be assigned to a user in the application.
 * It is used for managing user access control and permissions.
 *
 * Available roles:
 * - ROLE_USER: Represents a standard user of the system.
 * - ROLE_ADMIN: Represents an administrator with elevated privileges.
 */
public enum Role {
    ROLE_USER, ROLE_ADMIN
}
